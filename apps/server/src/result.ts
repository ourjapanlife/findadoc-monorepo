export type Result<T> = {
    data: T,
    hasErrors: boolean,
    errors?: Error[]
}

export type Error = {
    field: string,
    errorCode: ErrorCode,
    httpStatus?: number,
    /** How many rows the error is about, such as the bookings that keep a facility from being deleted. */
    count?: number,
}

